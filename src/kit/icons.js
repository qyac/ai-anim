/** 全部图标名（`anim icons` 用） */
export const ICON_NAMES = Object.keys(ICONS);

/**
 * 把图标画进 LineBatch。
 * @param {any} lines LineBatch
 * @param {string} name 图标名（写错会抛，并列出可用的）
 * @param {number} x @param {number} y 左上角（24×24 方格的左上）
 * @param {number} size 方格边长（像素）
 * @param {number[]} color 线性色（可带 a）
 * @param {{ lw?: number, cx?: number, cy?: number }} [opts] lw = 线宽（默认 size/12）
 */
export function drawIcon(lines, name, x, y, size, color, opts = {}) {
  const poly = ICONS[name];
  if (!poly) {
    throw new Error('没有这个图标：' + name + '（可用：' + ICON_NAMES.join(' / ') + '）');
  }
  const s = size / 24;
  const cx = opts.cx ?? 12, cy = opts.cy ?? 12;
  const lw = opts.lw ?? Math.max(1.2, size / 12);
  for (const pl of poly) {
    if (pl.length === 2) {
      // 单点 = 实心小点（用极短线段画，线段批没有 point 原语）
      const px = x + (pl[0] - cx) * s, py = y + (pl[1] - cy) * s;
      lines.seg(px, py, px + 0.01, py, lw * 1.6, color);
      continue;
    }
    for (let i = 0; i + 3 < pl.length; i += 2) {
      lines.seg(
        x + (pl[i] - cx) * s, y + (pl[i + 1] - cy) * s,
        x + (pl[i + 2] - cx) * s, y + (pl[i + 3] - cy) * s,
        lw, color,
      );
    }
  }
}

/** 图标的外接尺寸（24×24 格子按 size 换算后就是 size，留在这里给排版用） */
export function iconBox(size) {
  return { w: size, h: size };
}
