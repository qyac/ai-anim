/**
 * `src/kit/icons.js` —— **内置矢量图标库**（24×24 网格，折线定义，不依赖任何文件）。
 *
 * 为什么要有它：镜头模板里到处在"手画"同一个箭头 / 同一个勾，每个模板各画一遍，
 * 粗细和比例都不一致。图标库把这件事变成一行：`drawIcon(lines, 'check', x, y, 40, color)`。
 *
 * 为什么用折线而不是 SVG 文件：
 *   · **确定性**：折线是常数，进 `lines`（LineBatch）后和别的矢量同批提交，
 *     不涉及 IO、不影响首帧、不破坏 `render(t)` 纯函数；
 *   · **可换色/换粗细**：颜色是参数，跟调色板走；
 *   · **零素材**：不用管字体、SVG 解析、许可文件。
 *
 * 每个图标是 `[[x0,y0,x1,y1,…], …]`，坐标在 24×24 的方格里（左上原点，y 向下），
 * 也支持单点数组（长度 2）= 画一个实心点。
 *
 * ```js
 * import { drawIcon, ICON_NAMES } from '../kit/icons.js';
 * drawIcon(lines, 'cat', 120, 200, 48, css(P.bone));
 * ```
 */

